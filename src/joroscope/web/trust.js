// A plain-text sheet an astrologer can check in any software: the inputs, every graha to the arc
// second with its speed, the KP cusps and the sensitivity table
function exportCalculationSheet() {
  const c = currentChart;
  if (!c?.calculation) return;
  const pad = (s, n) => String(s).padEnd(n);
  const lines = [`JoRoScope calculation sheet · ${c.profile?.name || ''}`.trim(), ''];
  calcSheetRows(c).forEach(([k, v]) => lines.push(`${pad(k, 24)} ${v}`));
  lines.push('', 'Grahas (sidereal longitudes)', pad('Graha', 10) + pad('Sign', 12) + pad('Longitude', 16) + pad('In sign', 14) + pad('Speed °/day', 13) + 'Star / pada');
  PRINT_GRAHAS.forEach(g => {
    const p = c.planets[g];
    if (!p) return;
    lines.push(pad(g, 10) + pad(p.sign, 12) + pad(formatDegrees(p.longitude), 16) + pad(formatDegrees(p.degree), 14)
      + pad(g === 'Ascendant' ? '' : `${p.speed.toFixed(4)}${p.retrograde ? ' R' : ''}`, 13) + `${p.nakshatra} ${p.pada}`);
  });
  if (c.kp_cusps?.length) {
    lines.push('', 'KP cusps (Placidus, Krishnamurti ayanamsa)');
    c.kp_cusps.forEach((lon, i) => lines.push(pad(`Cusp ${i + 1}`, 10) + formatDegrees(lon)));
  }
  if (c.bhava_chakra?.madhya?.length) {
    lines.push('', 'Bhava madhya (Sripati)');
    c.bhava_chakra.madhya.forEach((lon, i) => lines.push(pad(`Bhava ${i + 1}`, 10) + formatDegrees(lon)));
  }
  const s = c.sensitivity;
  if (s) {
    lines.push('', 'Birth-time sensitivity (minutes until a change)');
    s.quantities.forEach(r => lines.push(pad(SENS_LABELS[r.key][0], 16) + pad(sensLabel(r, 'value'), 18)
      + `earlier ${pad(minutesText(r.earlier, r.limit), 10)} later ${minutesText(r.later, r.limit)}`));
    lines.push(`Lagna moves ${s.lagna_arcmin_per_minute}′ per minute; every Dasa date moves ${s.dasa_days_per_minute} days per minute of birth time.`);
  }
  lines.push('', `Generated by JoRoScope ${c.calculation.app_version} with ${c.calculation.engine}.`);
  downloadText(`JoRoScope-Calculation-${(c.profile?.name || 'chart').replace(/\W+/g, '-')}.txt`, lines.join('\n'), 'text/plain');
}

